export function flagFromMMSI(mmsi) {
  const s = String(mmsi ?? '');
  const mid = Number(s.slice(0, 3));
  const hit = MID[mid];
  if (!hit) return { country: 'Unknown registry', code: null, mid: mid || null };
  return { country: hit[0], code: hit[1], mid };
}

// Emoji flag from a two-letter ISO code, via regional indicator symbols.
export function flagEmoji(code) {
  if (!code || code.length !== 2) return '\u2690'; // white flag
  return String.fromCodePoint(...[...code.toUpperCase()].map(c => 0x1f1e6 + c.charCodeAt(0) - 65));
}
